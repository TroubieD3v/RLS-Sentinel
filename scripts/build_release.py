#!/usr/bin/env python3
"""Build the distributable wheel + sdist with the web UI and bundled fixtures included.

Steps (each is skipped with a flag, never silently):
  1. build the React UI (`npm ci && npm run build`)         --skip-ui
  2. copy frontend/dist -> backend/rls_sentinel/_bundled/ui and fixtures/ -> .../_bundled/fixtures
  3. `python -m build` -> dist/*.whl, dist/*.tar.gz
  4. write dist/SHA256SUMS

The `_bundled` directory is a temporary build artefact (git-ignored, removed after the build). Run from anywhere:  python scripts/build_release.py
"""
from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BACKEND, FRONTEND, FIXTURES = ROOT / "backend", ROOT / "frontend", ROOT / "fixtures"
BUNDLED = BACKEND / "rls_sentinel" / "_bundled"
NPM = "npm.cmd" if sys.platform == "win32" else "npm"


def run(cmd: list[str], cwd: Path) -> None:
    print("+", " ".join(cmd), f"(in {cwd.relative_to(ROOT) if cwd != ROOT else '.'})", flush=True)
    subprocess.run(cmd, cwd=cwd, check=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--skip-ui", action="store_true", help="reuse an existing frontend/dist")
    ap.add_argument("--out", type=Path, default=ROOT / "dist")
    a = ap.parse_args()

    if not a.skip_ui:
        run([NPM, "ci"], FRONTEND)
        run([NPM, "run", "build"], FRONTEND)
    dist = FRONTEND / "dist"
    if not (dist / "index.html").is_file():
        raise SystemExit("frontend/dist/index.html is missing; run without --skip-ui")

    if BUNDLED.exists():
        shutil.rmtree(BUNDLED)
    shutil.copytree(dist, BUNDLED / "ui")
    shutil.copytree(FIXTURES, BUNDLED / "fixtures", ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    (BUNDLED / "__init__.py").write_text('"""Build artefact: web UI and bundled synthetic fixtures (generated by scripts/build_release.py)."""\n', encoding="utf-8")

    out: Path = a.out
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    run([sys.executable, "-m", "build", "--outdir", str(out), str(BACKEND)], ROOT)

    # The bundled copy is only needed while building. Leaving it behind would shadow frontend/dist and fixtures/ in a
    # development checkout with stale files.
    shutil.rmtree(BUNDLED, ignore_errors=True)

    sums = []
    for f in sorted(out.iterdir()):
        if f.suffix in {".whl", ".gz"}:
            sums.append(f"{hashlib.sha256(f.read_bytes()).hexdigest()}  {f.name}")
    (out / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")
    print("\n".join(sums))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
