"""Generate an executable pytest regression suite from a spec (F21)."""

from __future__ import annotations

import json
from textwrap import dedent

from ..expectations.models import Spec
from ..harness.results import RunResult


def generate_pytest(spec: Spec, *, fixture: str, variant: str, run: RunResult | None = None, mode: str = "spec") -> str:
    """``mode='spec'``: every expectation must PASS. ``mode='pin'``: pin each case to the status observed in ``run``."""
    ids = [e.id for e in spec.expectations]
    pinned = {c.case_id: c.status for c in run.cases} if (run and mode == "pin") else {}
    spec_json = json.dumps(spec.model_dump(mode="json"), indent=2, ensure_ascii=False)
    return dedent(f'''\
        """Generated by RLS Sentinel - authorization regression suite for fixture '{fixture}' ({variant}).

        Run:  pytest -q {"test_rls_authorization.py"}
        Needs PostgreSQL server binaries, Docker or SENTINEL_FIXTURE_ADMIN_URL (+ SENTINEL_FIXTURE_DISPOSABLE=true).
        Mode: {mode}. All statements execute inside a disposable database; nothing touches a source database.
        """
        import json

        import pytest

        from rls_sentinel.config import load_settings
        from rls_sentinel.expectations.models import Spec
        from rls_sentinel.service import run_fixture_test

        FIXTURE = {fixture!r}
        VARIANT = {variant!r}
        SPEC = Spec.model_validate(json.loads({spec_json!r}))
        CASE_IDS = {ids!r}
        PINNED = {pinned!r}


        @pytest.fixture(scope="module")
        def results():
            run, _snapshot = run_fixture_test(load_settings(), FIXTURE, VARIANT, spec=SPEC)
            assert run.isolation.no_fixture_drift, "fixture drift detected"
            return {{c.case_id: c for c in run.cases}}


        @pytest.mark.parametrize("case_id", CASE_IDS)
        def test_authorization_case(results, case_id):
            case = results[case_id]
            if PINNED:
                assert case.status == PINNED[case_id], f"{{case_id}}: {{case.status}} != pinned {{PINNED[case_id]}} ({{case.reason}})"
            else:
                assert case.status == "PASS", f"{{case_id}}: {{case.status}} - {{case.reason}}"
        ''')
